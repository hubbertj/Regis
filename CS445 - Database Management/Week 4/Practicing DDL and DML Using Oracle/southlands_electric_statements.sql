-- A query that lists each customer by name with location addresses.

SELECT "cu"."CustomerID" "Cutomer ID", 
       "lo"."Address"    "Address", 
       "lo"."Street"     "Street", 
       "lo"."City"       "City", 
       "lo"."State"      "State", 
       "lo"."Zipcode"    "Zipcode", 
       "lo"."Telephone"  "Telephone" 
FROM   "Customer" "cu" 
       left join "Location" "lo" 
              ON "lo"."CustomerID" = "cu"."CustomerID" 
ORDER  BY "cu"."CustomerID"; 

-- A query that lists the location type and the rates by time of day.

SELECT (SELECT "lt"."Name" 
        FROM   "Location_Type" "lt" 
        WHERE  "lo"."Type" = "lt"."LocationTypeID") "Location Type Name", 
       "lo"."LocationID"                            "Location ID", 
       "rt"."RatePerKWH"                            "Rate Per Hour" 
FROM   "Rate" "rt", 
       "Location" "lo" 
WHERE  "rt"."LocationID" = "lo"."LocationID" 
ORDER  BY "lo"."LocationID"; 



