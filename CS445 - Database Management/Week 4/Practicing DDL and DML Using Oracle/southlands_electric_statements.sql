-- Create all tables

CREATE TABLE "Customer" (
    "CustomerID" NUMBER GENERATED by default on null as IDENTITY,
    "Address" VARCHAR2(255)   NOT NULL,
    "Street" VARCHAR2(255)   NOT NULL,
    "City" VARCHAR2(255)    NULL,
    "State" VARCHAR2(255)    NULL,
    "Zipcode" VARCHAR2(255)    NULL,
    "Telephone" VARCHAR2(255)   NULL,
    CONSTRAINT "pk_Customer" PRIMARY KEY (
        "CustomerID"
     )
);

CREATE TABLE "Location" (
    "LocationID" NUMBER GENERATED by default on null as IDENTITY,
    "CustomerID" int   NOT NULL,
    "Address" VARCHAR2(255)   NOT NULL,
    "Street" VARCHAR2(255)   NOT NULL,
    "City" VARCHAR2(255)   NULL,
    "State" VARCHAR2(255)   NULL,
    "Zipcode" VARCHAR2(255)   NULL,
    "Telephone" VARCHAR2(255)   NULL,
    "Type" NUMBER   NOT NULL,
    CONSTRAINT "pk_Location" PRIMARY KEY (
        "LocationID"
     )
);

CREATE TABLE "Location_Type" (
    "LocationTypeID" NUMBER GENERATED by default on null as IDENTITY,
    "Name" VARCHAR2(255)   NOT NULL,
    "Description" VARCHAR2(255)   NULL,
    CONSTRAINT "pk_Location_Type" PRIMARY KEY (
        "LocationTypeID"
     )
);

CREATE TABLE "Rate" (
    "RateID" NUMBER GENERATED by default on null as IDENTITY,
    "Name" VARCHAR2(255)   NOT NULL,
    "RatePerKWH" int   NULL,
    "LocationID" NUMBER   NOT NULL,
    CONSTRAINT "pk_Rate" PRIMARY KEY (
        "RateID"
     )
);

ALTER TABLE "Location" ADD CONSTRAINT "fk_Location_CustomerID" FOREIGN KEY("CustomerID")
REFERENCES "Customer" ("CustomerID");

ALTER TABLE "Location" ADD CONSTRAINT "fk_Location_Type" FOREIGN KEY("Type")
REFERENCES "Location_Type" ("LocationTypeID");

ALTER TABLE "Rate" ADD CONSTRAINT "fk_Rate_LocationID" FOREIGN KEY("LocationID")
REFERENCES "Location" ("LocationID");

CREATE INDEX "idx_Customer_Address"
ON "Customer" ("Address");

CREATE INDEX "idx_Location_Address"
ON "Location" ("Address");

